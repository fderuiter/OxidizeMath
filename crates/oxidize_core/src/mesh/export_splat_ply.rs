//! INRIA / `SuperSplat` binary little-endian 3D Gaussian Splatting (`.ply`) serializer.

use super::export::invalid_mesh_error;
use super::types::Point3D;
use std::fmt::Write as _;
use std::io::Error;

/// Zeroth-order real spherical harmonic constant $C_0 = \frac{1}{2\sqrt{\pi}}$.
pub const SH_C0: f32 = 0.282_094_8;

/// Portable 3D Gaussian splat export record parameterized in world space.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct GaussianSplatPly {
    /// World-space Gaussian mean $\mu = (x, y, z)$.
    pub mean: Point3D,
    /// Positive principal semi-axis scales $(s_x, s_y, s_z)$ prior to log encoding.
    pub scale: Point3D,
    /// Scalar-first quaternion $[w, x, y, z]$ corresponding to `rot_0..rot_3`.
    pub rotation: [f32; 4],
    /// Linear opacity $\alpha \in (0, 1)$ prior to inverse-sigmoid logit encoding.
    pub opacity: f32,
    /// Linear RGB radiance $[r, g, b] \in [0, 1]^3$ converted to DC spherical harmonics.
    pub color: [f32; 3],
}

fn build_splat_ply_header(vertex_count: usize) -> String {
    let mut h = String::with_capacity(512);
    h.push_str("ply\nformat binary_little_endian 1.0\n");
    h.push_str("comment Generated by OxidizeMath 3DGS exporter\n");
    let _ = writeln!(h, "element vertex {vertex_count}");
    for prop in [
        "x", "y", "z", "nx", "ny", "nz", "f_dc_0", "f_dc_1", "f_dc_2", "opacity", "scale_0",
        "scale_1", "scale_2", "rot_0", "rot_1", "rot_2", "rot_3",
    ] {
        let _ = writeln!(h, "property float {prop}");
    }
    h.push_str("end_header\n");
    h
}

fn normalize_quat(q: [f32; 4]) -> [f32; 4] {
    let norm_sq = q[0] * q[0] + q[1] * q[1] + q[2] * q[2] + q[3] * q[3];
    if norm_sq.is_finite() && norm_sq > 1.0e-12 {
        let inv = 1.0 / norm_sq.sqrt();
        [q[0] * inv, q[1] * inv, q[2] * inv, q[3] * inv]
    } else {
        [1.0, 0.0, 0.0, 0.0]
    }
}

fn validate_splat(splat: &GaussianSplatPly) -> Result<(), Error> {
    if !splat.mean.is_finite() || !splat.scale.is_finite() {
        return Err(invalid_mesh_error(
            "Gaussian splat mean and scale must be finite",
        ));
    }
    if splat.scale.x <= 0.0 || splat.scale.y <= 0.0 || splat.scale.z <= 0.0 {
        return Err(invalid_mesh_error(
            "Gaussian splat scales must be strictly positive",
        ));
    }
    if !splat.opacity.is_finite()
        || !splat.rotation.iter().all(|v| v.is_finite())
        || !splat.color.iter().all(|v| v.is_finite())
    {
        return Err(invalid_mesh_error(
            "Gaussian splat opacity, rotation, and color must be finite",
        ));
    }
    Ok(())
}

/// Serializes 3D Gaussian splats into an INRIA / `SuperSplat` binary little-endian `.ply` payload.
pub fn export_splats_to_ply_binary(splats: &[GaussianSplatPly]) -> Result<Vec<u8>, Error> {
    if splats.is_empty() {
        return Err(invalid_mesh_error(
            "Cannot export empty 3D Gaussian splat scene",
        ));
    }
    for splat in splats {
        validate_splat(splat)?;
    }

    let header = build_splat_ply_header(splats.len());
    let mut out = Vec::with_capacity(header.len() + splats.len() * 68);
    out.extend_from_slice(header.as_bytes());

    for splat in splats {
        let dc0 = (splat.color[0].clamp(0.0, 1.0) - 0.5) / SH_C0;
        let dc1 = (splat.color[1].clamp(0.0, 1.0) - 0.5) / SH_C0;
        let dc2 = (splat.color[2].clamp(0.0, 1.0) - 0.5) / SH_C0;
        let alpha = splat.opacity.clamp(1.0e-6, 1.0 - 1.0e-6);
        let logit_opacity = (alpha / (1.0 - alpha)).ln();
        let s0 = splat.scale.x.max(1.0e-8).ln();
        let s1 = splat.scale.y.max(1.0e-8).ln();
        let s2 = splat.scale.z.max(1.0e-8).ln();
        let [r0, r1, r2, r3] = normalize_quat(splat.rotation);

        let fields = [
            splat.mean.x,
            splat.mean.y,
            splat.mean.z,
            0.0_f32,
            0.0_f32,
            0.0_f32,
            dc0,
            dc1,
            dc2,
            logit_opacity,
            s0,
            s1,
            s2,
            r0,
            r1,
            r2,
            r3,
        ];
        for f in fields {
            out.extend_from_slice(&f.to_le_bytes());
        }
    }

    Ok(out)
}
