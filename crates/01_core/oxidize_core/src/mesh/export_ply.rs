//! Binary little-endian and ASCII Polygon File Format (`.ply`) mesh serializers.

use super::export::{invalid_mesh_error, sanitized_vertex_normals, validate_mesh_geometry};
use super::types::{ColoredMesh, Mesh, VertexColor};
use std::fmt::Write as _;
use std::io::Error;

fn build_ply_header(
    format_tag: &str,
    vertex_count: usize,
    face_count: usize,
    has_color: bool,
) -> String {
    let mut header = String::with_capacity(256);
    header.push_str("ply\n");
    let _ = writeln!(header, "format {format_tag} 1.0");
    header.push_str("comment Generated by OxidizeMath\n");
    let _ = writeln!(header, "element vertex {vertex_count}");
    header.push_str("property float x\nproperty float y\nproperty float z\n");
    header.push_str("property float nx\nproperty float ny\nproperty float nz\n");
    if has_color {
        header.push_str("property uchar red\nproperty uchar green\nproperty uchar blue\n");
    }
    let _ = writeln!(header, "element face {face_count}");
    header.push_str("property list uchar uint vertex_indices\nend_header\n");
    header
}

fn validate_ply_counts(mesh: &Mesh, colors: Option<&[VertexColor]>) -> Result<(), Error> {
    validate_mesh_geometry(mesh, true)?;
    if u32::try_from(mesh.vertices.len()).is_err() {
        return Err(invalid_mesh_error("PLY vertex count exceeds u32::MAX"));
    }
    if let Some(cols) = colors
        && cols.len() != mesh.vertices.len()
    {
        return Err(invalid_mesh_error(
            "ColoredMesh colors length must equal mesh.vertices length",
        ));
    }
    Ok(())
}

fn serialize_ply_binary(mesh: &Mesh, colors: Option<&[VertexColor]>) -> Result<Vec<u8>, Error> {
    validate_ply_counts(mesh, colors)?;
    let normals = sanitized_vertex_normals(mesh);
    let (triangles, _) = mesh.indices.as_chunks::<3>();
    let header = build_ply_header(
        "binary_little_endian",
        mesh.vertices.len(),
        triangles.len(),
        colors.is_some(),
    );

    let v_stride = if colors.is_some() { 27 } else { 24 };
    let mut out =
        Vec::with_capacity(header.len() + mesh.vertices.len() * v_stride + triangles.len() * 13);
    out.extend_from_slice(header.as_bytes());

    for (idx, v) in mesh.vertices.iter().enumerate() {
        let n = normals[idx];
        for val in [v.x, v.y, v.z, n.x, n.y, n.z] {
            out.extend_from_slice(&val.to_le_bytes());
        }
        if let Some(cols) = colors {
            let c = cols[idx];
            out.extend_from_slice(&[c.r, c.g, c.b]);
        }
    }

    for &[i0, i1, i2] in triangles {
        out.push(3_u8);
        out.extend_from_slice(&(i0 as u32).to_le_bytes());
        out.extend_from_slice(&(i1 as u32).to_le_bytes());
        out.extend_from_slice(&(i2 as u32).to_le_bytes());
    }

    Ok(out)
}

fn serialize_ply_ascii(mesh: &Mesh, colors: Option<&[VertexColor]>) -> Result<String, Error> {
    validate_ply_counts(mesh, colors)?;
    let normals = sanitized_vertex_normals(mesh);
    let (triangles, _) = mesh.indices.as_chunks::<3>();
    let header = build_ply_header(
        "ascii",
        mesh.vertices.len(),
        triangles.len(),
        colors.is_some(),
    );

    let mut out =
        String::with_capacity(header.len() + mesh.vertices.len() * 64 + triangles.len() * 24);
    out.push_str(&header);

    for (idx, v) in mesh.vertices.iter().enumerate() {
        let n = normals[idx];
        if let Some(cols) = colors {
            let c = cols[idx];
            let _ = writeln!(
                out,
                "{:.6} {:.6} {:.6} {:.6} {:.6} {:.6} {} {} {}",
                v.x, v.y, v.z, n.x, n.y, n.z, c.r, c.g, c.b
            );
        } else {
            let _ = writeln!(
                out,
                "{:.6} {:.6} {:.6} {:.6} {:.6} {:.6}",
                v.x, v.y, v.z, n.x, n.y, n.z
            );
        }
    }

    for &[i0, i1, i2] in triangles {
        let _ = writeln!(out, "3 {i0} {i1} {i2}");
    }

    Ok(out)
}

/// Serializes an uncolored [`Mesh`] into binary little-endian `.ply` bytes.
pub fn export_mesh_to_ply_binary(mesh: &Mesh) -> Result<Vec<u8>, Error> {
    serialize_ply_binary(mesh, None)
}

/// Serializes an uncolored [`Mesh`] into ASCII `.ply` text.
pub fn export_mesh_to_ply_ascii(mesh: &Mesh) -> Result<String, Error> {
    serialize_ply_ascii(mesh, None)
}

/// Serializes a per-vertex [`ColoredMesh`] into binary little-endian `.ply` bytes.
pub fn export_colored_mesh_to_ply_binary(colored: &ColoredMesh) -> Result<Vec<u8>, Error> {
    serialize_ply_binary(&colored.mesh, Some(&colored.colors))
}

/// Serializes a per-vertex [`ColoredMesh`] into ASCII `.ply` text.
pub fn export_colored_mesh_to_ply_ascii(colored: &ColoredMesh) -> Result<String, Error> {
    serialize_ply_ascii(&colored.mesh, Some(&colored.colors))
}
