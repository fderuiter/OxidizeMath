/// Domain errors returned by hyperbolic geometry constructors and solvers.
#[derive(Clone, Debug, PartialEq)]
pub enum HyperbolicError {
    /// Coordinate lies on or outside the unit Poincaré disk boundary $|z| \ge 1$ or is non-finite.
    InvalidDiskPoint {
        /// Real coordinate $\operatorname{Re}(z)$.
        re: f64,
        /// Imaginary coordinate $\operatorname{Im}(z)$.
        im: f64,
    },
    /// Coordinate fails the upper half-plane condition $\operatorname{Im}(w) > 0$ or is non-finite.
    InvalidHalfPlanePoint {
        /// Real coordinate $\operatorname{Re}(w)$.
        re: f64,
        /// Imaginary coordinate $\operatorname{Im}(w)$.
        im: f64,
    },
    /// Matrix determinant is non-positive or non-finite, preventing normalization into `PSU(1,1)` or `PSL(2,R)`.
    DegenerateIsometry {
        /// Evaluated determinant $|a|^2 - |b|^2$ or $\alpha\delta - \beta\gamma$.
        determinant: f64,
    },
    /// Schläfli symbol `{p, q}` violates the negative-curvature condition $(p - 2)(q - 2) > 4$ or $q < 3$.
    NonHyperbolicSchlafli {
        /// Polygon edge count ($0$ denotes $\infty$ in `{infinity, q}`).
        p: u32,
        /// Vertex valence $q$.
        q: u32,
    },
    /// Polygon vertex list has fewer than 3 vertices, degenerate coincident vertices, or points outside $\overline{\mathbb{D}}$.
    InvalidPolygon {
        /// Human-readable reason describing the invalid polygon input.
        reason: &'static str,
    },
    /// Horocycle parameters are degenerate (non-unit ideal basepoint or radius outside $(0, 1)$).
    InvalidHorocycle {
        /// Human-readable reason describing the invalid horocycle input.
        reason: &'static str,
    },
    /// Billiard configuration has out-of-range side count or non-positive perturbation.
    InvalidBilliardConfig {
        /// Human-readable reason describing the invalid billiard setup.
        reason: &'static str,
    },
}

impl fmt::Display for HyperbolicError {
    #[verified_engine::verified]
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        assert!(!std::ptr::eq(self, std::ptr::null()));
        match self {
            Self::InvalidDiskPoint { re, im } => write!(
                f,
                "invalid Poincare disk point ({re}, {im}): requires finite coordinates with |z| < 1"
            ),
            Self::InvalidHalfPlanePoint { re, im } => write!(
                f,
                "invalid upper half-plane point ({re}, {im}): requires finite coordinates with Im(w) > 0"
            ),
            Self::DegenerateIsometry { determinant } => write!(
                f,
                "degenerate hyperbolic isometry matrix (determinant = {determinant})"
            ),
            Self::NonHyperbolicSchlafli { p, q } => write!(
                f,
                "Schlafli symbol {{{p}, {q}}} is not hyperbolic: requires p >= 3, q >= 3, and (p - 2)*(q - 2) > 4"
            ),
            Self::InvalidPolygon { reason } => write!(f, "invalid hyperbolic polygon: {reason}"),
            Self::InvalidHorocycle { reason } => write!(f, "invalid horocycle: {reason}"),
            Self::InvalidBilliardConfig { reason } => {
                write!(f, "invalid geodesic billiard configuration: {reason}")
            }
        }
    }
}

impl std::error::Error for HyperbolicError {}
