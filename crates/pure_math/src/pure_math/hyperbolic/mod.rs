// [cite:pure_math]
//! # Hyperbolic Geometry ($K = -1$)
//!
//! Verified models, conformal isometries, geodesics, horocycles, Coxeter Schläfli tilings,
//! and chaotic geodesic billiards on the hyperbolic plane $\mathbb{H}^2$ of constant
//! Gaussian curvature $K = -1$.
//!
//! ## Example
//!
//! ```rust
//! # use pure_math::__doctest_facade as math_explorer;
//! use math_explorer::pure_math::hyperbolic::{
//!     DiskPoint, Psu11, cayley_disk_to_half_plane, hyperbolic_distance_disk,
//!     hyperbolic_distance_half_plane, regular_polygon_vertices, gauss_bonnet_polygon_area,
//! };
//!
//! let p = DiskPoint::new(0.2, -0.15).expect("interior disk point");
//! let q = DiskPoint::new(-0.35, 0.4).expect("interior disk point");
//! let d_disk = hyperbolic_distance_disk(p, q);
//!
//! // Möbius transformations in PSU(1,1) preserve hyperbolic distance
//! let iso = Psu11::drag_between(p, DiskPoint::origin());
//! let d_moved = hyperbolic_distance_disk(iso.apply(p), iso.apply(q));
//! assert!((d_disk - d_moved).abs() < 1e-12);
//!
//! // Cayley transform is an exact isometry onto the upper half-plane
//! let d_hp = hyperbolic_distance_half_plane(
//!     cayley_disk_to_half_plane(p),
//!     cayley_disk_to_half_plane(q),
//! );
//! assert!((d_disk - d_hp).abs() < 1e-12);
//!
//! // Gauss-Bonnet area of a regular {7, 3} hyperbolic heptagon is pi * (7 - 2 - 14/3) = pi / 3
//! let heptagon = regular_polygon_vertices(7, 3).expect("valid {7,3} polygon");
//! let area = gauss_bonnet_polygon_area(&heptagon).expect("valid polygon area");
//! assert!((area - std::f64::consts::PI / 3.0).abs() < 1e-12);
//! ```

