//! Parameter-calibrated LaTeX, Rust 2024, and Python (`numpy`) code export for [`super::RiemannIntegrationTool`].

#![cfg_attr(any(), verified(opt_out = "gui_tool"))]

use super::{FunctionPreset, RiemannIntegrationTool};
use crate::framework::{CodeArtifact, InteractiveTool};
use math_commons::ast::{format_latex_scalar, format_python_float, format_rust_f64};

impl RiemannIntegrationTool {
    pub(super) fn build_code_artifact(&self) -> Option<CodeArtifact> {
        if !self.has_finite_parameters() {
            return None;
        }
        let (f_tex, f_rs, f_py) = match self.preset {
            FunctionPreset::SinX => (r"\sin\left(x\right)", "x.sin()", "np.sin(x)"),
            FunctionPreset::XSquared => ("x^{2}", "x * x", "x ** 2"),
            FunctionPreset::EToX => ("e^{x}", "x.exp()", "np.exp(x)"),
        };

        let (symbolic_latex, calibrated_latex) = self.build_riemann_latex(f_tex)?;
        let rust_source = self.build_riemann_rust(f_rs)?;
        let python_source = self.build_riemann_python(f_py)?;

        Some(CodeArtifact {
            symbolic_latex,
            calibrated_latex,
            rust_source,
            python_source,
        })
    }

    fn build_riemann_latex(&self, f_tex: &str) -> Option<(String, String)> {
        let a_tex = format_latex_scalar(self.min_x).ok()?;
        let b_tex = format_latex_scalar(self.max_x).ok()?;
        let dx = (self.max_x - self.min_x) / (self.steps as f64);
        let dx_tex = format_latex_scalar(dx).ok()?;
        let res_tex = format_latex_scalar(self.result).ok()?;

        let symbolic = format!(
            "\\begin{{aligned}}\nI &= \\int_{{a}}^{{b}} {f_tex}\\,dx \\approx \\frac{{\\Delta x}}{{2}}\\left(f(a) + 2\\sum_{{i=1}}^{{N-1}} f(a + i\\Delta x) + f(b)\\right)\n\\end{{aligned}}"
        );
        let calibrated = format!(
            "\\begin{{aligned}}\nI &= \\int_{{{a_tex}}}^{{{b_tex}}} {f_tex}\\,dx \\\\\nN &= {}, \\quad \\Delta x = {dx_tex}, \\quad T_N \\approx {res_tex}\n\\end{{aligned}}",
            self.steps
        );
        Some((symbolic, calibrated))
    }

    fn build_riemann_rust(&self, f_rs: &str) -> Option<String> {
        let a_rs = format_rust_f64(self.min_x).ok()?;
        let b_rs = format_rust_f64(self.max_x).ok()?;
        Some(format!(
            "// Standalone Rust 2024 composite trapezoidal quadrature generated by OxidizeMath\n\
             pub fn integrand(x: f64) -> f64 {{\n\
             \x20   {f_rs}\n\
             }}\n\n\
             pub fn composite_trapezoidal(a: f64, b: f64, steps: usize) -> f64 {{\n\
             \x20   let dx = (b - a) / (steps as f64);\n\
             \x20   let mut sum = 0.5 * (integrand(a) + integrand(b));\n\
             \x20   for i in 1..steps {{\n\
             \x20       sum += integrand(a + (i as f64) * dx);\n\
             \x20   }}\n\
             \x20   sum * dx\n\
             }}\n\n\
             fn main() {{\n\
             \x20   let area = composite_trapezoidal({a_rs}, {b_rs}, {});\n\
             \x20   println!(\"Trapezoidal integral = {{area:.9}}\");\n\
             }}\n",
            self.steps
        ))
    }

    fn build_riemann_python(&self, f_py: &str) -> Option<String> {
        let a_py = format_python_float(self.min_x).ok()?;
        let b_py = format_python_float(self.max_x).ok()?;
        Some(format!(
            "\"\"\"Standalone Python composite trapezoidal quadrature generated by OxidizeMath.\"\"\"\n\
             import numpy as np\n\n\
             def integrand(x: float | np.ndarray):\n\
             \x20   return {f_py}\n\n\
             def composite_trapezoidal(a: float, b: float, steps: int) -> float:\n\
             \x20   xs = np.linspace(a, b, steps + 1, dtype=np.float64)\n\
             \x20   ys = integrand(xs)\n\
             \x20   dx = (b - a) / float(steps)\n\
             \x20   return float(dx * (0.5 * ys[0] + np.sum(ys[1:-1]) + 0.5 * ys[-1]))\n\n\
             if __name__ == \"__main__\":\n\
             \x20   area = composite_trapezoidal({a_py}, {b_py}, {})\n\
             \x20   print(f\"Trapezoidal integral = {{area:.9f}}\")\n",
            self.steps
        ))
    }
}
