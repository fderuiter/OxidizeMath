//! Parameter-calibrated LaTeX, Rust 2024, and Python (`scipy`) code export for [`super::SirTool`].

#![cfg_attr(any(), verified(opt_out = "gui_tool"))]

use super::{SirTool, MAX_SIR_DURATION, MAX_SIR_STEPS, MIN_SIR_DURATION};
use crate::framework::{CodeArtifact, InteractiveTool};
use math_commons::ast::{format_latex_scalar, format_python_float, format_rust_f64};
use scientific_metadata::theory::{ParameterConstraint, TheoryDescribable};
use std::collections::HashMap;

struct SirSpec {
    n: f64,
    s0: f64,
    i0: f64,
    beta: f64,
    gamma: f64,
    dt: f64,
    steps: usize,
    horizon: f64,
}

impl SirTool {
    pub(super) fn build_code_artifact(&self) -> Option<CodeArtifact> {
        if !self.has_finite_parameters() {
            return None;
        }
        let n = self.n.max(1.0);
        let i0 = self.i0.clamp(0.0, n);
        let dt = 0.1_f64;
        let raw_steps = self.duration / dt;
        if !raw_steps.is_finite() || raw_steps < 0.0 {
            return None;
        }
        let steps = raw_steps.min(MAX_SIR_STEPS as f64) as usize;
        let spec = SirSpec {
            n,
            s0: n - i0,
            i0,
            beta: self.beta.max(0.0),
            gamma: self.gamma.max(0.0),
            dt,
            steps,
            horizon: (steps as f64) * dt,
        };

        let (symbolic_latex, calibrated_latex) = build_sir_latex(&spec)?;
        let rust_source = build_sir_rust(&spec)?;
        let python_source = build_sir_python(&spec)?;

        Some(CodeArtifact {
            symbolic_latex,
            calibrated_latex,
            rust_source,
            python_source,
        })
    }
}

fn build_sir_latex(spec: &SirSpec) -> Option<(String, String)> {
    let n_tex = format_latex_scalar(spec.n).ok()?;
    let s0_tex = format_latex_scalar(spec.s0).ok()?;
    let i0_tex = format_latex_scalar(spec.i0).ok()?;
    let beta_tex = format_latex_scalar(spec.beta).ok()?;
    let gamma_tex = format_latex_scalar(spec.gamma).ok()?;
    let dur_tex = format_latex_scalar(spec.horizon).ok()?;

    let symbolic = "\\begin{aligned}\n\\frac{dS}{dt} &= -\\frac{\\beta S I}{N} \\\\\n\\frac{dI}{dt} &= \\frac{\\beta S I}{N} - \\gamma I \\\\\n\\frac{dR}{dt} &= \\gamma I\n\\end{aligned}".to_string();
    let calibrated = format!(
        "\\begin{{aligned}}\n\\frac{{dS}}{{dt}} &= -\\frac{{{beta_tex} \\cdot S \\cdot I}}{{{n_tex}}} \\\\\n\\frac{{dI}}{{dt}} &= \\frac{{{beta_tex} \\cdot S \\cdot I}}{{{n_tex}}} - {gamma_tex} \\cdot I \\\\\n\\frac{{dR}}{{dt}} &= {gamma_tex} \\cdot I \\\\\nS(0) &= {s0_tex}, \\quad I(0) = {i0_tex}, \\quad R(0) = 0, \\quad t \\in [0, {dur_tex}]\n\\end{{aligned}}"
    );
    Some((symbolic, calibrated))
}

fn build_sir_rust(spec: &SirSpec) -> Option<String> {
    let n_rs = format_rust_f64(spec.n).ok()?;
    let s0_rs = format_rust_f64(spec.s0).ok()?;
    let i0_rs = format_rust_f64(spec.i0).ok()?;
    let beta_rs = format_rust_f64(spec.beta).ok()?;
    let gamma_rs = format_rust_f64(spec.gamma).ok()?;
    let dt_rs = format_rust_f64(spec.dt).ok()?;
    let steps = spec.steps;
    Some(format!(
        "// Standalone Rust 2024 Kermack-McKendrick SIR RK4 solver generated by OxidizeMath\n\
         pub const N_POP: f64 = {n_rs};\n\
         pub const BETA: f64 = {beta_rs};\n\
         pub const GAMMA: f64 = {gamma_rs};\n\n\
         pub fn sir_rhs(_t: f64, state: [f64; 3]) -> [f64; 3] {{\n\
         \x20   let [s, i, _r] = state;\n\
         \x20   let inf = BETA * s * i / N_POP;\n\
         \x20   let rec = GAMMA * i;\n\
         \x20   [-inf, inf - rec, rec]\n\
         }}\n\n\
         pub fn rk4_step(t: f64, state: [f64; 3], dt: f64) -> [f64; 3] {{\n\
         \x20   let k1 = sir_rhs(t, state);\n\
         \x20   let k2 = sir_rhs(t + 0.5 * dt, [state[0] + 0.5 * dt * k1[0], state[1] + 0.5 * dt * k1[1], state[2] + 0.5 * dt * k1[2]]);\n\
         \x20   let k3 = sir_rhs(t + 0.5 * dt, [state[0] + 0.5 * dt * k2[0], state[1] + 0.5 * dt * k2[1], state[2] + 0.5 * dt * k2[2]]);\n\
         \x20   let k4 = sir_rhs(t + dt, [state[0] + dt * k3[0], state[1] + dt * k3[1], state[2] + dt * k3[2]]);\n\
         \x20   [\n\
         \x20       state[0] + (dt / 6.0) * (k1[0] + 2.0 * k2[0] + 2.0 * k3[0] + k4[0]),\n\
         \x20       state[1] + (dt / 6.0) * (k1[1] + 2.0 * k2[1] + 2.0 * k3[1] + k4[1]),\n\
         \x20       state[2] + (dt / 6.0) * (k1[2] + 2.0 * k2[2] + 2.0 * k3[2] + k4[2]),\n\
         \x20   ]\n\
         }}\n\n\
         fn main() {{\n\
         \x20   let dt: f64 = {dt_rs};\n\
         \x20   let steps: usize = {steps};\n\
         \x20   let mut state: [f64; 3] = [{s0_rs}, {i0_rs}, 0.0_f64];\n\
         \x20   for step in 0..=steps {{\n\
         \x20       let t = (step as f64) * dt;\n\
         \x20       println!(\"{{t:.2}},{{:.6}},{{:.6}},{{:.6}}\", state[0], state[1], state[2]);\n\
         \x20       if step < steps {{\n\
         \x20           state = rk4_step(t, state, dt);\n\
         \x20       }}\n\
         \x20   }}\n\
         }}\n"
    ))
}

fn build_sir_python(spec: &SirSpec) -> Option<String> {
    let n_py = format_python_float(spec.n).ok()?;
    let s0_py = format_python_float(spec.s0).ok()?;
    let i0_py = format_python_float(spec.i0).ok()?;
    let beta_py = format_python_float(spec.beta).ok()?;
    let gamma_py = format_python_float(spec.gamma).ok()?;
    let hor_py = format_python_float(spec.horizon).ok()?;
    let num_pts = spec.steps.saturating_add(1);
    Some(format!(
        "\"\"\"Standalone Python Kermack-McKendrick SIR solver generated by OxidizeMath.\"\"\"\n\
         import numpy as np\n\
         from scipy.integrate import solve_ivp\n\n\
         N_POP = {n_py}\n\
         BETA = {beta_py}\n\
         GAMMA = {gamma_py}\n\n\
         def sir_rhs(t: float, y: np.ndarray) -> list[float]:\n\
         \x20   s, i, _r = float(y[0]), float(y[1]), float(y[2])\n\
         \x20   inf = BETA * s * i / N_POP\n\
         \x20   rec = GAMMA * i\n\
         \x20   return [-inf, inf - rec, rec]\n\n\
         t_eval = np.linspace(0.0, {hor_py}, {num_pts})\n\
         sol = solve_ivp(sir_rhs, (0.0, {hor_py}), [{s0_py}, {i0_py}, 0.0], t_eval=t_eval, method=\"RK45\", rtol=1e-9, atol=1e-12)\n\n\
         if __name__ == \"__main__\":\n\
         \x20   print(f\"Final SIR({{sol.t[-1]:.1f}}) = ({{sol.y[0, -1]:.4f}}, {{sol.y[1, -1]:.4f}}, {{sol.y[2, -1]:.4f}})\")\n"
    ))
}

impl TheoryDescribable for SirTool {
    fn theory_description(&self) -> String {
        let r0 = self.beta / self.gamma;
        format!(
            "Kermack-McKendrick SIR compartmental epidemic model: $\\frac{{dS}}{{dt}} = -\\frac{{\\beta S I}}{{N}}$, $\\frac{{dI}}{{dt}} = \\frac{{\\beta S I}}{{N}} - \\gamma I$, $\\frac{{dR}}{{dt}} = \\gamma I$. Transmission rate $\\beta = {:.3}$, recovery rate $\\gamma = {:.3}$, basic reproduction number $R_0 = {:.2}$.",
            self.beta, self.gamma, r0
        )
    }

    fn phonetic_description(&self) -> String {
        "Kermack-McKendrick SIR compartmental epidemic model theory".into()
    }

    fn theory_citation(&self) -> String {
        "A Contribution to the Mathematical Theory of Epidemics (Kermack & McKendrick, 1927)".into()
    }

    fn available_descriptions(&self) -> HashMap<String, String> {
        HashMap::new()
    }

    fn theory_parameters(&self) -> HashMap<String, ParameterConstraint> {
        [
            ("N", 100.0, 100_000.0, 100.0),
            ("I0", 1.0, 50_000.0, 1.0),
            ("beta", 0.0, 5.0, 0.02),
            ("gamma", 0.0, 1.0, 0.01),
            ("duration", MIN_SIR_DURATION, MAX_SIR_DURATION, 1.0),
        ]
        .into_iter()
        .map(|(k, min, max, step)| (k.to_string(), ParameterConstraint { min, max, step }))
        .collect()
    }
}
