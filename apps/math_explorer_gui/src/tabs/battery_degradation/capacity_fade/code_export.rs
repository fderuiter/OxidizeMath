//! Parameter-calibrated LaTeX, Rust 2024, and Python code artifact generation for [`super::CapacityFadeTool`].

#![cfg_attr(any(), verified(opt_out = "gui_tool"))]

use super::CapacityFadeTool;
use crate::framework::{CodeArtifact, InteractiveTool};
use math_commons::ast::{format_latex_scalar, format_python_float, format_rust_f64};
use math_explorer::engineering::battery_degradation::{
    DepthOfDischarge, ElectrochemicalAgingModel,
};

impl CapacityFadeTool {
    pub(super) fn build_code_artifact(&self) -> Option<CodeArtifact> {
        if !self.has_finite_parameters() || self.dod <= 0.0 {
            return None;
        }
        let model = self.active_model();
        let n70 = DepthOfDischarge::new(self.dod)
            .ok()
            .map(|d| model.n70(d).as_f64())?;
        let dod_tex = format_latex_scalar(self.dod).ok()?;
        let alpha_tex = format_latex_scalar(model.alpha()).ok()?;
        let beta_tex = format_latex_scalar(model.beta()).ok()?;
        let z_tex = format_latex_scalar(model.exponent_z()).ok()?;
        let temp_tex = format_latex_scalar(model.temperature_c()).ok()?;
        let crate_tex = format_latex_scalar(model.c_rate()).ok()?;
        let n70_tex = format_latex_scalar(n70).ok()?;
        let cyc_tex = format_latex_scalar(self.cycles_to_simulate).ok()?;

        let symbolic_latex = "\\begin{aligned}\nN_{70}(D, T, I_c) &= \\frac{\\alpha \\cdot D^{\\beta}}{\\exp\\!\\left(\\frac{E_a}{R}\\left(\\frac{1}{T_{\\text{ref}}} - \\frac{1}{T}\\right)\\right) I_c^{\\gamma_c}} \\\\\nC(N) &= 1 - 0.3\\left(\\frac{N}{N_{70}(D, T, I_c)}\\right)^{z}\n\\end{aligned}".to_string();
        let calibrated_latex = format!(
            "\\begin{{aligned}}\nN_{{70}}({dod_tex}\\%, {temp_tex}\\,^\\circ\\text{{C}}, {crate_tex}\\text{{C}}) &= \\frac{{{alpha_tex} \\cdot {dod_tex}^{{{beta_tex}}}}}{{A_T({temp_tex}\\,^\\circ\\text{{C}}) \\cdot {crate_tex}^{{\\gamma_c}}}} \\approx {n70_tex} \\\\\nC(N) &= 1 - 0.3\\left(\\frac{{N}}{{{n70_tex}}}\\right)^{{{z_tex}}}, \\quad N \\in [0, {cyc_tex}]\n\\end{{aligned}}"
        );
        let rust_source = self.build_capacity_rust(&model)?;
        let python_source = self.build_capacity_python(&model)?;

        Some(CodeArtifact {
            symbolic_latex,
            calibrated_latex,
            rust_source,
            python_source,
        })
    }

    fn build_capacity_rust(&self, model: &ElectrochemicalAgingModel) -> Option<String> {
        let alpha_rs = format_rust_f64(model.alpha()).ok()?;
        let beta_rs = format_rust_f64(model.beta()).ok()?;
        let z_rs = format_rust_f64(model.exponent_z()).ok()?;
        let ea_rs = format_rust_f64(model.activation_energy()).ok()?;
        let gc_rs = format_rust_f64(model.c_rate_exponent()).ok()?;
        let temp_rs = format_rust_f64(model.temperature_c()).ok()?;
        let crate_rs = format_rust_f64(model.c_rate()).ok()?;
        let dod_rs = format_rust_f64(self.dod).ok()?;
        let cyc_rs = format_rust_f64(self.cycles_to_simulate).ok()?;
        Some(format!(
            "// Standalone Rust 2024 coupled Li-ion capacity fade model generated by OxidizeMath\n\
             pub const ALPHA: f64 = {alpha_rs};\n\
             pub const BETA: f64 = {beta_rs};\n\
             pub const EXPONENT_Z: f64 = {z_rs};\n\
             pub const ACTIVATION_ENERGY_J_MOL: f64 = {ea_rs};\n\
             pub const C_RATE_EXPONENT: f64 = {gc_rs};\n\
             pub const GAS_CONSTANT_R: f64 = 8.314_462_618_f64;\n\
             pub const REF_TEMP_K: f64 = 298.15_f64;\n\n\
             pub fn n70_cycles(dod_pct: f64, temp_c: f64, c_rate: f64) -> f64 {{\n\
             \x20   let raw_d = dod_pct.clamp(1.0e-4, 100.0);\n\
             \x20   let temp_k = temp_c.clamp(-20.0, 60.0) + 273.15;\n\
             \x20   let arrhenius = ((ACTIVATION_ENERGY_J_MOL / GAS_CONSTANT_R) * (1.0 / REF_TEMP_K - 1.0 / temp_k)).exp();\n\
             \x20   let stress = (arrhenius * c_rate.clamp(0.05, 10.0).powf(C_RATE_EXPONENT)).max(1.0e-12);\n\
             \x20   ((ALPHA * raw_d.powf(BETA)) / stress).max(0.0)\n\
             }}\n\n\
             pub fn capacity_retention(cycles: f64, dod_pct: f64, temp_c: f64, c_rate: f64) -> f64 {{\n\
             \x20   if cycles <= 0.0 || dod_pct <= 0.0 {{\n\
             \x20       return 1.0;\n\
             \x20   }}\n\
             \x20   let n70 = n70_cycles(dod_pct, temp_c, c_rate);\n\
             \x20   if n70 <= 0.0 {{\n\
             \x20       return 0.0;\n\
             \x20   }}\n\
             \x20   (1.0 - (0.3 * (cycles / n70).powf(EXPONENT_Z)).clamp(0.0, 1.0)).clamp(0.0, 1.0)\n\
             }}\n\n\
             fn main() {{\n\
             \x20   let dod: f64 = {dod_rs};\n\
             \x20   let temp_c: f64 = {temp_rs};\n\
             \x20   let c_rate: f64 = {crate_rs};\n\
             \x20   let max_cycles: f64 = {cyc_rs};\n\
             \x20   for i in 0..=100 {{\n\
             \x20       let c = (max_cycles / 100.0) * (i as f64);\n\
             \x20       println!(\"{{c:.1}},{{:.9}}\", capacity_retention(c, dod, temp_c, c_rate));\n\
             \x20   }}\n\
             }}\n"
        ))
    }

    fn build_capacity_python(&self, model: &ElectrochemicalAgingModel) -> Option<String> {
        let alpha_py = format_python_float(model.alpha()).ok()?;
        let beta_py = format_python_float(model.beta()).ok()?;
        let z_py = format_python_float(model.exponent_z()).ok()?;
        let ea_py = format_python_float(model.activation_energy()).ok()?;
        let gc_py = format_python_float(model.c_rate_exponent()).ok()?;
        let temp_py = format_python_float(model.temperature_c()).ok()?;
        let crate_py = format_python_float(model.c_rate()).ok()?;
        let dod_py = format_python_float(self.dod).ok()?;
        let cyc_py = format_python_float(self.cycles_to_simulate).ok()?;
        Some(format!(
            "\"\"\"Standalone Python coupled Li-ion capacity fade model generated by OxidizeMath.\"\"\"\n\
             import numpy as np\n\n\
             ALPHA = {alpha_py}\n\
             BETA = {beta_py}\n\
             EXPONENT_Z = {z_py}\n\
             ACTIVATION_ENERGY_J_MOL = {ea_py}\n\
             C_RATE_EXPONENT = {gc_py}\n\
             GAS_CONSTANT_R = 8.314462618\n\
             REF_TEMP_K = 298.15\n\n\
             def n70_cycles(dod_pct: float, temp_c: float, c_rate: float) -> float:\n\
             \x20   raw_d = float(np.clip(dod_pct, 1.0e-4, 100.0))\n\
             \x20   temp_k = float(np.clip(temp_c, -20.0, 60.0)) + 273.15\n\
             \x20   arrhenius = float(np.exp((ACTIVATION_ENERGY_J_MOL / GAS_CONSTANT_R) * (1.0 / REF_TEMP_K - 1.0 / temp_k)))\n\
             \x20   stress = max(1.0e-12, arrhenius * (float(np.clip(c_rate, 0.05, 10.0)) ** C_RATE_EXPONENT))\n\
             \x20   return float(max(0.0, (ALPHA * (raw_d ** BETA)) / stress))\n\n\
             def capacity_retention(cycles: float | np.ndarray, dod_pct: float, temp_c: float, c_rate: float):\n\
             \x20   if dod_pct <= 0.0:\n\
             \x20       return np.ones_like(cycles, dtype=np.float64)\n\
             \x20   n70 = n70_cycles(dod_pct, temp_c, c_rate)\n\
             \x20   if n70 <= 0.0:\n\
             \x20       return np.zeros_like(cycles, dtype=np.float64)\n\
             \x20   loss = np.clip(0.3 * ((np.maximum(cycles, 0.0) / n70) ** EXPONENT_Z), 0.0, 1.0)\n\
             \x20   return np.clip(1.0 - loss, 0.0, 1.0)\n\n\
             if __name__ == \"__main__\":\n\
             \x20   cycles = np.linspace(0.0, {cyc_py}, 101)\n\
             \x20   soh = capacity_retention(cycles, {dod_py}, {temp_py}, {crate_py})\n\
             \x20   n70 = n70_cycles({dod_py}, {temp_py}, {crate_py})\n\
             \x20   print(f\"N70={{n70:.1f}} cycles, final SoH={{float(soh[-1]):.9f}}\")\n"
        ))
    }
}
