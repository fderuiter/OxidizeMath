fn read_build_script_output(out_dir: &Path) -> String {
    let parent_dir = out_dir
        .parent()
        .expect("OUT_DIR must have a parent build directory");
    let build_output_path = [
        parent_dir.join("output"),
        parent_dir.join("run").join("stdout"),
    ]
    .into_iter()
    .find(|p| p.is_file())
    .expect("Cargo build script output file must exist");
    fs::read_to_string(&build_output_path).expect("Cargo build script output file must be readable")
}

#[test]
fn test_inventory_tabs_preserve_deterministic_slug_order() {
    let tabs = instantiate_tabs();
    assert!(!tabs.is_empty(), "Traceability tab is always enabled");
    let slugs: Vec<&str> = tabs.iter().map(|t| t.url_slug()).collect();
    let unique: HashSet<&str> = slugs.iter().copied().collect();
    assert_eq!(unique.len(), tabs.len(), "Tab slugs must be unique");

    let expected_slugs: Vec<&str> = super::sorted_tab_descriptors()
        .into_iter()
        .map(|d| d.id)
        .collect();
    assert_eq!(
        slugs, expected_slugs,
        "Instantiated tabs must follow deterministic (order, id) descriptor order"
    );

    for (idx, tab) in tabs.iter().enumerate() {
        let single = instantiate_tab(idx).expect("instantiate_tab must resolve valid index");
        assert_eq!(single.name(), tab.name());
        assert_eq!(single.url_slug(), tab.url_slug());
    }
    assert!(instantiate_tab(tabs.len()).is_none());

    #[cfg(all(
        feature = "pure_math",
        feature = "applied",
        feature = "ai",
        feature = "biology",
        feature = "climate",
        feature = "epidemiology",
        feature = "physics"
    ))]
    {
        assert_eq!(tabs.len(), 32, "All 32 GUI domain tabs must register");
        assert_eq!(slugs.first().copied(), Some("quantum"));
        assert_eq!(slugs.last().copied(), Some("ai"));
    }
}

#[test]
fn test_build_script_emits_scoped_rerun_directives() {
    let out_dir = Path::new(env!("OUT_DIR"));
    assert!(
        !out_dir.join("generated_tabs.rs").exists(),
        "OUT_DIR/generated_tabs.rs must no longer be generated"
    );
    let manifest = fs::read_to_string(out_dir.join("traceability_manifest.json"))
        .expect("OUT_DIR/traceability_manifest.json must be generated by build.rs");
    assert!(manifest.contains("\"paper_coverage\""));

    let build_output = read_build_script_output(out_dir);
    let rerun_paths: HashSet<&str> = build_output
        .lines()
        .filter_map(|line| line.strip_prefix("cargo:rerun-if-changed="))
        .collect();

    for path in &rerun_paths {
        assert!(!path.trim().is_empty(), "rerun directive must not be empty");
        assert!(
            !path.contains('\\'),
            "rerun path must use forward slashes: {path}"
        );
    }

    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let ws_root = oxidize_core::workspace::find_workspace_root_from(manifest_dir)
        .expect("workspace root must be discoverable");
    let canon_manifest =
        fs::canonicalize(manifest_dir).unwrap_or_else(|_| manifest_dir.to_path_buf());
    let canon_ws = fs::canonicalize(&ws_root).unwrap_or_else(|_| ws_root.clone());
    let depth = canon_manifest
        .strip_prefix(&canon_ws)
        .expect("manifest must live in workspace")
        .components()
        .count();
    let rel_prefix = "../".repeat(depth);

    for local_expected in [
        "build.rs",
        "build_snapshot.rs",
        "build_stage.rs",
        "src/tabs/mod.rs",
    ] {
        assert!(
            rerun_paths.contains(local_expected),
            "Missing expected cargo:rerun-if-changed={local_expected} in math_explorer_gui output"
        );
    }

    for ws_expected in ["traceability.toml", "papers"] {
        let expected = format!("{rel_prefix}{ws_expected}");
        assert!(
            rerun_paths.contains(expected.as_str()),
            "Missing expected cargo:rerun-if-changed={expected} in math_explorer_gui output"
        );
    }
    assert_scoped_package_rerun_directives(&ws_root, &rel_prefix, &rerun_paths);
}

fn assert_scoped_package_rerun_directives(
    ws_root: &Path,
    rel_prefix: &str,
    rerun_paths: &HashSet<&str>,
) {
    let packages = oxidize_core::workspace::discover_workspace_packages(ws_root)
        .expect("workspace packages must load");
    let member_of = |pkg_name: &str| -> String {
        packages
            .iter()
            .find(|p| p.package_name == pkg_name)
            .map(|p| format!("{rel_prefix}{}/src", p.member_path))
            .expect("expected package in workspace")
    };

    for expected_pkg in [
        "math_rng",
        "engine_linalg",
        "federated_registry",
        "oxidize_core",
        "math_commons",
        "scientific_metadata",
        "diagnostics",
    ] {
        let expected = member_of(expected_pkg);
        assert!(
            rerun_paths.contains(expected.as_str()),
            "missing {expected}"
        );
    }

    #[cfg(any(
        feature = "ai",
        feature = "applied",
        feature = "biology",
        feature = "physics",
        feature = "pure_math"
    ))]
    for engine_pkg in ["engine_diffeq", "engine_pde"] {
        let expected = member_of(engine_pkg);
        assert!(
            rerun_paths.contains(expected.as_str()),
            "missing {expected}"
        );
    }

    assert!(!rerun_paths.contains("Cargo.toml"));
    for excluded_pkg in [
        "unified_verification",
        "markdown_tests",
        "verified_engine",
        "verified_engine_macros",
        "xtask",
    ] {
        let excluded = member_of(excluded_pkg);
        assert!(
            !rerun_paths.contains(excluded.as_str()),
            "unexpected {excluded}"
        );
    }
}

#[cfg(not(target_arch = "wasm32"))]
#[test]
fn test_domain_features_transitively_emit_tier2_engine_rerun_dirs() {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let ws_root = oxidize_core::workspace::find_workspace_root_from(manifest_dir)
        .expect("workspace root must be discoverable");
    for feat in ["ai", "applied", "biology", "physics"] {
        let enabled = std::collections::BTreeSet::from([feat.to_string()]);
        let dirs = oxidize_core::workspace::compute_gui_snapshot_code_dirs(
            &ws_root,
            "math_explorer_gui",
            &enabled,
        )
        .expect("compute_gui_snapshot_code_dirs must succeed");
        assert!(
            dirs.iter().any(|d| d.ends_with("engine_diffeq/src")),
            "GUI feature `{feat}` must emit rerun path for engine_diffeq/src: {dirs:?}"
        );
        assert!(
            dirs.iter().any(|d| d.ends_with("engine_pde/src")),
            "GUI feature `{feat}` must emit rerun path for engine_pde/src: {dirs:?}"
        );
    }
}

fn collect_static_mod_gates(mod_rs: &str) -> std::collections::BTreeMap<String, Option<String>> {
    let mut gates = std::collections::BTreeMap::new();
    let mut active_cfg = None;
    for line in mod_rs.lines() {
        let clean = line.split("//").next().unwrap_or("").trim();
        if clean.is_empty() {
            continue;
        }
        if let Some(feat) = clean
            .strip_prefix("#[cfg(feature = \"")
            .and_then(|s| s.strip_suffix("\")]"))
        {
            active_cfg = Some(feat.to_string());
        } else if let Some(name) = clean
            .strip_prefix("pub mod ")
            .and_then(|s| s.strip_suffix(';'))
        {
            gates.insert(name.trim().to_string(), active_cfg.take());
        } else if !clean.starts_with("#[") {
            active_cfg = None;
        }
    }
    gates
}

#[test]
fn test_static_tab_modules_match_filesystem_tabs_and_inventory_descriptors() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR must be set");
    let tabs_dir = Path::new(&manifest_dir).join("src/tabs");
    let mod_rs = fs::read_to_string(tabs_dir.join("mod.rs")).expect("read src/tabs/mod.rs");
    let declared = collect_static_mod_gates(&mod_rs);
    let mut discovered = std::collections::BTreeSet::new();

    for entry in fs::read_dir(&tabs_dir).expect("read src/tabs").flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if matches!(name.as_str(), "mod.rs" | "tests.rs") {
            continue;
        }
        let (mod_name, target) = if path.is_dir() {
            (name, path.join("mod.rs"))
        } else if let Some(stem) = name.strip_suffix(".rs") {
            (stem.to_string(), path)
        } else {
            continue;
        };
        let Ok(src) = fs::read_to_string(&target) else {
            continue;
        };
        let has_tab_impl = src.lines().any(|l| {
            l.contains("impl ExplorerTab for ") || l.contains("impl crate::tabs::ExplorerTab for ")
        });
        if !has_tab_impl {
            continue;
        }
        assert!(
            src.contains("TabDescriptor"),
            "ExplorerTab module `{mod_name}` must submit a static TabDescriptor via inventory"
        );
        discovered.insert(mod_name);
    }

    let declared_names: std::collections::BTreeSet<String> = declared.keys().cloned().collect();
    assert_eq!(
        discovered.len(),
        32,
        "Expected all 32 local GUI tab modules"
    );
    assert_eq!(
        declared_names, discovered,
        "Static `pub mod` declarations in src/tabs/mod.rs must match local ExplorerTab modules"
    );
    assert_eq!(
        declared.get("traceability"),
        Some(&None),
        "traceability tab must remain unconditionally enabled"
    );
}
